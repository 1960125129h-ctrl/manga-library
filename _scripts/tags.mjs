/* 从书名里抽"作品"候选: 圆括号/方括号/#话题, 过滤停用词和作者名 */
const norm2 = (s) => String(s || '').replace(/[\[\]()（）]/g, ' ').replace(/\s+/g, ' ').trim();
export function badCandidate(t, authorSet) {
  if (t.length < 2 || t.length > 24) return true;
  if (STOP.test(t)) return true;
  if (/^[\d\s\-_.]+$/.test(t)) return true;
  if (/\.(com|net|vip|org|cc|me|info|xyz)$/i.test(t)) return true;                                  // 域名/站名
  if (/[,，、]/.test(t)) return true;
  if (/^(un)?censored|decensored|digital|colorized|english|translated|version|raw|hd$/i.test(t)) return true;
  if (LANG_RE.test(t)) return true;                                                                  // 语言类词(chinese/japanese/...)不是作品
  if (AI_WORDS.test(t) || AI_SKIP.test(t)) return true;                                             // AI 标记本身不是作品
  if (/(汉化组|漢化組|汉化|漢化|翻訳|翻译|翻譯|字幕组|嵌字|重嵌|扫图|修图|绅士仓库|核动力|航空战列舰|&|\+)/i.test(t)) return true;   // 汉化组/嵌字流水线
  if (/^(汉化|漢化|翻译|翻譯|嵌字|重嵌|扫图)/.test(t)) return true;
  if (/(^|[^a-z])(patreon|fantia|fanbox|gumroad|booth|dlsite|pixiv|ci-en|unifans|fanbox)([^a-z]|$)/i.test(t)) return true; // 付费平台/投稿站名不是作品
  if (/[「」『』《》〈〉【】]/.test(t)) return true;                // 候选本身还带角括号/书名号 -> 是副标题片段, 不是 IP
  /* ---- 垃圾候选护栏(2026-10-22): 自动学习曾把这些学成"作品", 污染了 149 本书的作品字段 ---- */
  if (/\d+;/.test(t)) return true;                                                       // HTML 实体残渣: #44; / #39;s / #039;s
  if (/^\d{2,}\s*[pP](?:ages?|ics?|s)?$/.test(t)) return true;                            // 页数标记: 160p / 11220P / 500pics
  if (/^#?[0-9A-Za-z]{14,}$/.test(t) && /\d/.test(t) && /[A-Za-z]/.test(t)) return true;     // 随机 hash/ID 串: #mdzLEBVz2J9T43DR5dpWRQ
  if (/^(?:ntr|nsfw|r-?18|fullsets?|all works?|storyline|re-?upload|reprint|unlimited|sample|preview|raws?|request|commission|collab|非纯爱)$/i.test(t)) return true;   // 题材/状态词
  if (/(?:paypal|zfb|alipay|wechat|wxpay|qqpay)/i.test(t)) return true;                    // 付款渠道: paypal/zfbwx
  const n = norm2(t);
  for (const a of (authorSet || [])) {
    const s = norm2(a);
    if (s.length < 2) continue;
    if (n === s || n.indexOf(s) >= 0 || s.indexOf(n) >= 0) return true;                            // 和作者/社团名撞了
  }
  return false;
}
export function candidates(title, authorSet) {
  const out = [];
  const s = String(title || '');
  const push = (v) => {
    const t = String(v || '').replace(/[\[\]()（）]/g, '').replace(/\s+/g, ' ').trim();
    if (badCandidate(t, authorSet)) return;
    if (out.indexOf(t) < 0) out.push(t);
  };
  (s.match(/\(([^)]{2,40})\)/g) || []).forEach((m) => push(m));
  (s.match(/\[([^\]]{2,40})\]/g) || []).forEach((m) => push(m));
  (s.match(/（([^）]{2,40})）/g) || []).forEach((m) => push(m));
  (s.match(/《([^》]{2,40})》/g) || []).forEach((m) => push(m));      // 书名号里的作品/角色名
  (s.match(/〈([^〉]{2,40})〉/g) || []).forEach((m) => push(m));
  (s.match(/【([^】]{2,40})】/g) || []).forEach((m) => push(m));
  (s.match(/「([^」]{2,40})」/g) || []).forEach((m) => push(m));
  (s.match(/#([^\s#]{2,30})/g) || []).forEach((m) => push(m));
  return out;
}

/* 自动学习: 同一候选在库里出现 >=2 次 -> 写进表的"自动"区 */
export function learn(LIB, tables, titles, authorSet) {
  const known = new Set();
  for (const w of tables.作品) { known.add(w.名); (w.别名 || []).forEach((a) => known.add(a)); }
  const cnt = {};
  for (const t of titles) for (const c of candidates(t, authorSet)) cnt[c] = (cnt[c] || 0) + 1;
  const added = [];
  for (const k of Object.keys(cnt)) {
    if (cnt[k] < 2) continue;
    if (known.has(k)) continue;
    // 与已知作品名/别名互为子串的不算新作品(プリンセスコネクト!Re_Dive 是"公主连结Re:Dive"的长变体)
    const overlap = [...known].some((k0) => {
      if (!k0 || k0.length < 4) return false;
      return k0.indexOf(k) >= 0 || k.indexOf(k0) >= 0;
    });
    if (overlap) continue;
    tables.作品.push({ 名: k, 别名: [], 来源: '自动' });
    known.add(k);
    added.push(k);
    if (added.length >= 200) break;
  }
  if (added.length) saveTables(LIB, tables);
  return added;
}

/* 联网刷新别名(AniList, 公开接口无需 key): 每次最多 limit 个新名字, 3 秒超时, 失败静默跳过 */
export async function refreshAliases(HERE, names, limit, log) {
  const cache = loadAliasCache(HERE);
  const todo = names.filter((n) => n && !cache[n]).slice(0, limit || 20);
  if (!todo.length) return 0;
  const t0 = Date.now();
  const BUDGET_MS = 3000;   // 联网总预算: 累计超过 3 秒就停, 剩下的下次再说
  let ok = 0;
  for (const n of todo) {
    if (Date.now() - t0 > BUDGET_MS) break;
    const ctl = new AbortController();
    const timer = setTimeout(() => ctl.abort(), 3000);
    try {
      const r = await fetch('https://graphql.anilist.co', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', 'Accept': 'application/json' },
        body: JSON.stringify({ query: 'query($s:String){Media(search:$s,type:ANIME){title{native romaji english} synonyms} Character(search:$s){name{native full first last alternative}}}', variables: { s: n } }),
        signal: ctl.signal,
      });
      clearTimeout(timer);
      if (r.ok) {
        const j = await r.json();
        const d = (j && j.data) || {};
        const al = [];
        const m = d.Media;
        if (m) { const t = m.title || {}; [t.native, t.romaji, t.english].forEach((x) => { if (x) al.push(x); }); (m.synonyms || []).forEach((x) => { if (x) al.push(x); }); }
        const ch = d.Character;
        if (ch) { const nm = ch.name || {}; [nm.native, nm.full, nm.first, nm.last].forEach((x) => { if (x) al.push(x); }); (nm.alternative || []).forEach((x) => { if (x) al.push(x); }); }
        cache[n] = Array.from(new Set(al)).slice(0, 12);
        ok++;
      }
    } catch (e) { clearTimeout(timer); break; }   // 没网/超时: 直接停, 不影响重建
  }
  saveAliasCache(HERE, cache);
  return ok;
}

/* 匹配作品/角色: 规范名 + 手动别名 + 联网缓存别名 + 自动别名 */
export function matchWT(text, tables, aliasCache) {
  // 剥掉 URL/链接, 避免 .io/.jp/.com 等域名后缀被误匹配
  // 剥掉方括号内容(社团名, 如 [ジャックとニコルソン (のりパチ)]) 和行首 event 标签(如 (C108))
  let raw = String(text || '').toLowerCase()
    .replace(/https?:\/\/\S+|www\.\S+/gi, ' ')
    .replace(/\[[^\]]*\]/g, ' ')
    .replace(/(?:^\s*\([^)]*\)\s*)+/g, ' ');
  const s = raw.replace(/\b\w+\.(io|jp|com|net|org|cn|cc|co|tv|me|app|dev|xyz|info|biz|ru|de|fr|uk|us)\b/gi, ' ');
  if (!s.trim()) return { work: '', char: '' };
  // 上下文作品: 扫描文本里出现了哪些已知作品名/别名, 这些作品的角色才允许匹配
  // 如 tag 里有 "blue archive" → 只匹配蔚蓝档案的角色, 排除刀剑神域的爱丽丝
  const ctxWorks = new Set();
  for (const w of tables.作品) {
    const wnames = [w.名].concat(w.别名 || []);
    for (const wn of wnames) {
      const wl = String(wn || '').toLowerCase().trim();
      if (wl.length < 2) continue;
      // 作品名做子串匹配(不需要词边界), 因为 tag 里就是 "blue archive" 这种
      if (s.indexOf(wl) >= 0) { ctxWorks.add(w.名); break; }
    }
  }
  // 打分: 命中的别名越长越可信("梓"这种一个字的名字打不过"ロキシー"/"早濑优香"); 同分时手动表 > 自动表
  const scoreOf = (entry) => {
    const names = [entry.名].concat(entry.别名 || []).concat((aliasCache && aliasCache[entry.名]) || []);
    let best = 0;
    for (const n of names) {
      const t = String(n || '').toLowerCase();
      if (t.length < 2) continue;
      // 纯假名 1-2 字符片段（ある/いる/あれ/これ/アル/イレ…）在日语文本里极常见，子串匹配必误命中，跳过
      if (t.length <= 2 && /^[ぁ-んァ-ヶー]+$/.test(t)) continue;
      let hit = false;
      if (/^[a-z][a-z0-9' -]*$/.test(t) && t.replace(/[^a-z]/g,'').length <= 5) {
        // 短英文/字母别名: 要求词边界, 避免 ines 命中 chinese / io 命中 violet / asuna 命中 asunaro / kaga 命中 kagami
        const esc = t.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
        hit = new RegExp('(?<![a-z0-9])' + esc + '(?![a-z0-9])').test(s);
      } else {
        hit = s.indexOf(t) >= 0;
      }
      if (hit && t.length > best) best = t.length;
    }
    return best;
  };
  const best = (list, isCharList) => {
    let name = '', sc = 0, man = false, entry = null;
    for (const e of list) {
      // 上下文作品限定: 如果文本里出现了已知作品名, 只匹配该作品的角色
      if (ctxWorks.size > 0 && isCharList) {
        if (!e.作品 || !ctxWorks.has(e.作品)) continue;
      }
      // 无上下文作品时: 短别名不参与匹配, 避免 izumi 命中和泉纱雾 / アリス 命中刀剑神域
      if (isCharList && ctxWorks.size === 0) {
        const names = [e.名].concat(e.别名 || []);
        const hasLongHit = names.some((n) => {
          const t = String(n || '').toLowerCase();
          if (t.length < 2) return false;
          if (t.length <= 2 && /^[ぁ-んァ-ヶー]+$/.test(t)) return false;
          const isShortEng = /^[a-z][a-z0-9' -]*$/.test(t) && t.replace(/[^a-z]/g, '').length <= 5;
          const isShortJp = /^[ぁ-んァ-ヶー]+$/.test(t) && t.length <= 3;
          return !(isShortEng || isShortJp) && s.indexOf(t) >= 0;
        });
        if (!hasLongHit) continue;
      }
      const k = scoreOf(e);
      if (!k) continue;
      const isMan = e.来源 !== '自动';
      if (k > sc || (k === sc && isMan && !man)) { sc = k; name = e.名; man = isMan; entry = e; }
    }
    return { name: name, score: sc, entry: entry };
  };
  const c = best(tables.角色, true);
  const w = best(tables.作品, false);
  let char = c.name, work = w.name;
  // 上下文里有作品名但角色/作品没匹配到: 用上下文作品
  if (ctxWorks.size > 0 && !work) {
    work = Array.from(ctxWorks)[0];
  }
  // 角色命中就以它所属作品为准(作品/角色同步): 否则会出现"洛琪希被塞进蔚蓝档案"
  if (c.entry && c.entry.作品) work = c.entry.作品;
  else if (!work && c.entry) work = '';
  return { work: work, char: char };
}

/* 角色自动学习: 对"作品已识别"的书, 从书名抽候选, 同一作品下出现 >=2 次 -> 认成该作品的角色 */
export function learnChars(LIB, tables, books, authorSet) {
  const have = new Set(tables.角色.map((c) => c.名));
  const workNames = new Set();
  for (const w of tables.作品) { workNames.add(w.名); (w.别名 || []).forEach((a) => workNames.add(a)); }
  for (const c of tables.角色) { have.add(c.名); (c.别名 || []).forEach((a) => have.add(a)); }
  for (const c of tables.角色) workNames.add(c.名);
  // 作品预发现: b.work 为空的书(作品表里还没收录的 IP), 反复出现的候选词先认成作品。
  // 否则这些书永远 work 为空, 角色学习这条"死角"覆盖不到。阈值保守(>=5次), 避免误判。
  {
    const cnt = {};
    const emptyBooks = [];
    for (const b of books) {
      if (b.work) continue;
      emptyBooks.push(b);
      for (const c of candidates(b.text, authorSet)) cnt[c] = (cnt[c] || 0) + 1;
    }
    for (const k of Object.keys(cnt)) {
      if (cnt[k] < 5 || workNames.has(k) || have.has(k)) continue;
      tables.作品.push({ 名: k, 别名: [], 来源: '自动' });
      workNames.add(k);
      have.add(k);
    }
    // 把新发现的作品回写到这些空 work 的书, 让后面按作品分组的角色学习能覆盖到
    for (const b of emptyBooks) {
      const m = matchWT(b.text, tables, undefined);
      if (m.work) b.work = m.work;
    }
  }
  const byWork = {};
  for (const b of books) { if (!b.work) continue; (byWork[b.work] = byWork[b.work] || []).push(b); }
  const added = [];
  for (const wk of Object.keys(byWork)) {
    const cnt = {};
    for (const b of byWork[wk]) for (const c of candidates(b.text, authorSet)) cnt[c] = (cnt[c] || 0) + 1;
    for (const k of Object.keys(cnt)) {
      if (cnt[k] < 3 || have.has(k) || k === wk || workNames.has(k)) continue;   // 出现>=3次, 且不能是已知作品名
      // 与已知作品名/别名互为子串的不算角色(プリンセスコネクト!Re_Dive 是作品全名, 不是角色)
      const overlap = [...workNames].some((wn) => wn && wn.length >= 4 && (wn.indexOf(k) >= 0 || k.indexOf(wn) >= 0));
      if (overlap) continue;
      tables.角色.push({ 名: k, 作品: wk, 别名: [], 来源: '自动' });
      have.add(k);
      added.push(wk + ' / ' + k);
      if (added.length >= 100) return (saveTables(LIB, tables), added);
    }
  }
  if (added.length) saveTables(LIB, tables);
  return added;
}
